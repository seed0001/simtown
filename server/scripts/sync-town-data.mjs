// Railway builds each service from an isolated subdirectory of the repo, so
// server/ can't reach across into client/ at deploy time the way it can when
// running locally. This script copies the handful of framework-free data
// modules the resident brains actually need into server/src/towndata/, so
// they travel with the server when it deploys.
//
// client/src/city/residents.ts stays the real source of truth for editing.
// Run `npm run sync-town-data` after changing it (or registry.ts / clock.ts)
// and commit the result — these copies are checked into git on purpose,
// since Railway never sees client/ when building this service.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const clientCity = join(here, '..', '..', 'client', 'src', 'city')
const clientSim = join(here, '..', '..', 'client', 'src', 'sim')
const outDir = join(here, '..', 'src', 'towndata')

// mirrors client/src/{city,sim}/ exactly, so the relative imports inside
// residents.ts ('./registry', '../sim/clock') resolve unchanged — these are
// verbatim copies plus a header, never rewritten.
const header = (sourcePath) =>
  `// GENERATED by server/scripts/sync-town-data.mjs from ${sourcePath}.\n// Do not hand-edit — edit the source file and re-run \`npm run sync-town-data\`.\n\n`

const files = [
  { from: join(clientCity, 'residents.ts'), to: join(outDir, 'city', 'residents.ts'), label: 'client/src/city/residents.ts' },
  { from: join(clientCity, 'registry.ts'), to: join(outDir, 'city', 'registry.ts'), label: 'client/src/city/registry.ts' },
  { from: join(clientSim, 'clock.ts'), to: join(outDir, 'sim', 'clock.ts'), label: 'client/src/sim/clock.ts' },
]

for (const f of files) {
  const source = readFileSync(f.from, 'utf-8')
  mkdirSync(dirname(f.to), { recursive: true })
  writeFileSync(f.to, header(f.label) + source, 'utf-8')
  console.log(`synced ${f.label}`)
}
